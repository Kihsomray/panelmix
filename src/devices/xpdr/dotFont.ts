/** Each glyph as a list of lit dots, built once. */
const DOTS: ReadonlyMap<string, readonly (readonly [number, number])[]> = new Map(
  Object.entries(GLYPHS).map(([ch, rows]) => [
    ch,
    rows.flatMap((row, y) => [...row].flatMap((c, x) => (c === '#' ? [[x, y] as const] : []))),
  ]),
);

/** Glyph advance in dots: five columns plus one of spacing. */
const ADVANCE = 6;

/** Width of a string drawn with dot size `px` (no trailing space). */
export function dotTextWidth(text: string, px: number): number {
  return text.length === 0 ? 0 : (text.length * ADVANCE - 1) * px;
}

/** Draws text with its top-left at (x, y); each dot is a `px` square. Unknown characters draw as blanks. */
export function drawDotText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, px: number): void {
  // Slightly smaller squares than the pitch leave the gaps that make it read as a dot matrix.
  const dot = px * 0.86;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    for (const [dx, dy] of DOTS.get(ch) ?? []) ctx.fillRect(cx + dx * px, y + dy * px, dot, dot);
    cx += ADVANCE * px;
  }
}

export type Align = 'left' | 'center' | 'right';

/** drawDotText with horizontal alignment about `x`. */
export function drawDotTextAligned(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, px: number, align: Align): void {
  const w = dotTextWidth(text, px);
  const left = align === 'left' ? x : align === 'center' ? x - w / 2 : x - w;
  drawDotText(ctx, text, left, y, px);
}
